function make(kind){
 if(kind==='grammar-roles')return sentenceParts.map(([sent,part,a,b,c],i)=>row(
  '밑의 문장에서 ‘'+part+'’는 어떤 문장 성분인가요?',a,b,c,
  '‘'+part+'’는 '+a+' 구실을 하고 있습니다.',sent));
 if(kind==='grammar-agreement')return negativeAgreement.map(([good,b,c,why],i)=>row(
  '앞의 말과 뒤의 서술어가 자연스럽게 호응하는 문장은?',good,b,c,why,'호응 관계 '+(i+1)));
 if(kind==='idioms')return idioms.map(([idiom,a,b,c])=>row('관용어 ‘'+idiom+'’의 뜻으로 알맞은 것은?',a,b,c,
  '‘'+idiom+'’는 글자 그대로보다 ‘'+a+'’라는 뜻으로 쓰입니다.'));
 if(kind==='proverbs')return proverbs.map(([proverb,a,b,c])=>row('속담 ‘'+proverb+'’의 뜻으로 알맞은 것은?',a,b,c,
  '‘'+proverb+'’는 ‘'+a+'’라는 뜻입니다.'));
 if(kind==='revision')return revision.map(([s,a,b,c,why])=>row('글을 바르게 고쳐 쓰는 방법으로 알맞은 것은?',a,b,c,why,s));
 if(kind==='spacing')return spacing.map(([a,b,c],i)=>row('띄어쓰기가 바른 문장은?',a,b,c,
  '조사와 의존 명사의 쓰임, 낱말 사이의 띄어쓰기를 살펴보면 ‘'+a+'’가 올바릅니다.','띄어쓰기 연습 '+(i+1)));
 if(kind==='argument')return evidence.map(([claim,a,b,c])=>row('다음 주장을 뒷받침하는 타당한 근거는?',a,b,c,
  '‘'+a+'’는 주장을 뒷받침하는 구체적이고 관련 있는 까닭입니다.','주장: '+claim));
 if(kind==='interview-nature')return interview.map(([s,a,b,c],i)=>row('상대방을 존중하며 정보를 얻는 면담 방법으로 알맞은 것은?',a,b,c,
  '면담은 사람을 만나 질문하고 답을 들으며 정보를 얻는 활동입니다. '+a,s));
 if(kind==='interview-process')return interview.map(([s,a,b,c],i)=>row('면담의 준비와 진행 과정에서 알맞은 행동은?',a,b,c,
  '면담의 목적과 절차에 따라 ‘'+a+'’와 같이 행동해야 합니다.','면담 상황 '+(i+1)+': '+s));
 if(kind==='language-medium')return mediaLanguage.map(([s,a,b,c])=>row('다음 상황에서 중심이 되는 언어의 형태는?',a,b,c,
  '‘'+s+'’에서는 주로 '+a+'를 사용합니다.',s));
 if(kind==='explain-structure')return explainStructures.map(([s,a,b,c],i)=>row(
  '설명 내용의 짜임으로 알맞은 것은?',a,b,c,'설명할 내용을 ‘'+a+'’의 관계로 배열하고 있습니다.',s));
 throw Error('Unknown upper grade Korean kind '+kind);
}
