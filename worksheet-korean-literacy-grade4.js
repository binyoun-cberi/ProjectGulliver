function make(kind){
 switch(kind){
 case 'claim':return argumentsData.map(([claim,valid,bad1,bad2])=>q('의견을 뒷받침하는 이유로 가장 알맞은 문장은?',valid,bad1,bad2,
    '‘'+valid+'’는 제시된 의견을 뒷받침하는 이유를 설명합니다.','의견: '+claim));
 case 'compare':return comparing.map(([a,b,answer,w1,w2])=>q('두 사람이 제시한 의견은 어떤 점에서 다른가요?',answer,w1,w2,
   '첫 번째 사람은 ‘'+a+'’라고, 두 번째 사람은 ‘'+b+'’라고 말합니다.','가: '+a+' / 나: '+b));
 case 'antonym':return antonyms.map(([word,answer,w1,w2])=>q('낱말 ‘'+word+'’와 뜻이 반대되는 낱말은?',answer,w1,w2,
   '‘'+word+'’의 반대되는 뜻을 가진 낱말은 ‘'+answer+'’입니다.'));
 case 'observe':return observation.map(([detail,answer,w1,w2])=>q('관찰한 내용을 사실대로 기록한 문장은?',answer,w1,w2,
   '‘'+answer+'’는 관찰하거나 측정한 내용을 구체적으로 나타낸 기록입니다.',detail));
 case 'polysemy':return meanings.map(([detail,word,answer,w1,w2])=>q('이 글에서 ‘'+word+'’는 어떤 뜻으로 쓰였나요?',answer,w1,w2,
   '문장의 앞뒤 내용을 살피면 ‘'+word+'’는 ‘'+answer+'’를 뜻합니다.',detail));
 case 'reference':return references.map(([detail,ref,answer,w1,w2,why])=>q('글에서 ‘'+ref+'’이/가 가리키는 대상은 무엇인가요?',answer,w1,w2,why,detail));
 case 'cause':return causality.map(([detail,question,answer,w1,w2])=>q(question,answer,w1,w2,
   '이 글에서 원인은 ‘'+answer+'’라는 점이며, 그로 인해 뒤의 일이 일어났습니다.',detail));
 case 'hangul':return hangul.map(([prompt,answer,w1,w2])=>q(prompt,answer,w1,w2,
   '한글 글자의 자음자와 모음자, 받침 등 글자의 짜임을 살펴보면 ‘'+answer+'’가 알맞습니다.'));
 case 'proposal':return proposals.map(([detail,answer,w1,w2])=>q('이 문제를 해결하기 위한 제안으로 적절한 것은?',answer,w1,w2,
   '문제를 실제로 개선하는 구체적인 행동을 제안해야 합니다. ‘'+answer+'’가 그 조건에 맞습니다.',detail));
 case 'online':return online.map(([detail,answer,w1,w2])=>q('온라인에서 지켜야 할 예절로 알맞은 행동은?',answer,w1,w2,
   '온라인 소통에서도 상대의 권리와 개인 정보를 보호하고 존중해야 합니다.',detail));
 case 'letter':return letters.map(([detail,answer,w1,w2])=>q('편지를 읽을 사람을 생각하여 쓸 내용으로 가장 알맞은 것은?',answer,w1,w2,
   '편지는 읽는 사람의 상황을 고려하여 마음과 필요한 내용을 전해야 합니다.',detail));
 case 'story':return stories.map(([detail,answer,w1,w2])=>q('앞에서 일어난 사건을 바탕으로 자연스럽게 이어지는 내용은?',answer,w1,w2,
   '앞에서 등장한 인물과 사건을 이어서 생각하면 ‘'+answer+'’처럼 이야기를 전개할 수 있습니다.',detail));
 default:throw Error('No grade-four literacy skill '+kind);
 }
}
