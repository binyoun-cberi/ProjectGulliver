function make(kind){
 switch(kind){
 case 'dialogue':return dialogue.map(([s,a,w1,w2])=>q('대화에서 상대방을 배려하는 방법으로 가장 알맞은 것은?',a,w1,w2,'상대의 말과 감정을 존중하고 대화의 차례를 지켜야 합니다. '+a,s));
 case 'omission':return omissions.map(([detail,p,a,w1,w2])=>q('대화에서 생략된 내용을 짐작하며 답해 보세요. '+p,a,w1,w2,'앞의 질문과 뒤의 짧은 대답을 함께 읽으면 생략된 말의 의미를 확인할 수 있습니다. 답은 ‘'+a+'’입니다.',detail));
 case 'time':return times.map(([detail,a,w1,w2])=>q('이 문장에서 나타나는 시간 표현의 성격은?',a,w1,w2,'‘'+detail+'’에서 '+a+'에 해당하는 시간 표현을 확인할 수 있습니다.',detail));
 case 'travel':return travel.map(([detail,a,w1,w2,why])=>q('기행문을 쓸 때 이 문장은 여정·견문·감상 중 무엇에 해당하나요?',a,w1,w2,why,detail));
 case 'select':return select.map(([detail,a,w1,w2])=>q('목적에 알맞고 확인 가능한 자료는 무엇인가요?',a,w1,w2,'조사 목적과 관련되어 있고 제공 기관이나 조사 시기를 확인할 수 있어야 합니다. '+a,detail));
 case 'dialect':return dialect.map(([detail,a,w1,w2])=>q('표준어와 방언을 대하는 태도로 알맞은 것은?',a,w1,w2,'방언은 지역 문화와 생활을 보여 주는 소중한 언어 자료입니다. '+a,detail));
 case 'credibility':return credibility.map(([detail,a,w1,w2])=>q('이 자료의 신뢰성을 판단하려면 어떻게 해야 하나요?',a,w1,w2,'작성자와 발행 시기, 근거 및 목적을 확인하는 태도가 필요합니다. '+a,detail));
 case 'compromise':return compromises.map(([detail,a,w1,w2])=>q('서로 다른 의견을 조정하는 방법으로 가장 적절한 것은?',a,w1,w2,'각자의 요구를 듣고 참여할 수 있는 방법을 함께 찾아야 합니다. '+a,detail));
 default:throw Error('Unknown grade-five activity '+kind);
 }
}
