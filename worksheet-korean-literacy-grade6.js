function make(kind){
 switch(kind){
 case 'revision':return revision.map(([detail,a,w1,w2])=>q('글을 고쳐 쓸 때 가장 알맞은 방법은?',a,w1,w2,'글의 내용과 구성을 다시 살펴 정확하고 이해하기 쉽게 고치는 것이 좋습니다. '+a,detail));
 case 'debate':return debate.map(([detail,a,w1,w2])=>q('토론의 절차와 규칙을 지키는 행동은?',a,w1,w2,'주장과 근거를 정확하게 전하고 상대의 발언권을 존중해야 합니다. '+a,detail));
 case 'evidence':return evidence.map(([claim,a,w1,w2])=>q('다음 주장을 뒷받침하는 타당한 근거는 무엇인가요?',a,w1,w2,'‘'+a+'’는 주장과 직접 관련된 이유나 결과를 설명합니다.','주장: '+claim));
 case 'idiom':return idioms.map(([detail,a,w1,w2])=>q('글에서 사용한 관용 표현의 뜻으로 알맞은 것은?',a,w1,w2,'글의 상황을 살펴보면 ‘'+a+'’라는 뜻입니다.',detail));
 case 'proverb':return proverbs.map(([p,a,w1,w2])=>q('속담 ‘'+p+'’의 뜻으로 가장 알맞은 것은?',a,w1,w2,'이 속담은 ‘'+a+'’라는 뜻으로 사용합니다.'));
 case 'citation':return citation.map(([detail,a,w1,w2])=>q('자료의 출처와 인용 방법을 바르게 지킨 것은?',a,w1,w2,'인용한 자료와 자신의 표현을 구분하고 자료의 출처를 정확하게 확인해야 합니다.',detail));
 case 'logic':return logic.map(([detail,a,w1,w2])=>q('글의 주장이나 근거에서 주의해야 할 점은?',a,w1,w2,'주장에 이르는 자료의 범위와 조사 조건을 확인해야 합니다. 이 글은 '+a,detail));
 case 'expression':return expressions.map(([detail,a,w1,w2])=>q('원래 뜻을 살리면서 정확하고 존중하는 표현으로 고친 것은?',a,w1,w2,'근거 없이 단정하거나 상대를 비난하기보다 사실을 확인하고 구체적으로 말해야 합니다.',detail));
 case 'interview':return interviews.map(([detail,a,w1,w2])=>q('면담 목적에 맞으면서 상대를 존중하는 질문은?',a,w1,w2,'면담은 목적에 필요한 정보를 구체적으로 묻되 편향되거나 사적인 질문을 피해야 합니다.',detail));
 case 'native':return nativeScenes.map(([detail,a],i)=>q('글에서 고유어를 사용했을 때의 표현 효과로 알맞은 것은?',a,'다른 종류의 낱말은 모두 틀렸다는 뜻입니다.','글의 뜻을 일부러 알아듣기 어렵게 만듭니다.','고유어에는 우리말 고유의 느낌이 담겨 있습니다. 다만 한자어와 외래어도 목적에 맞게 쓸 수 있습니다.',detail));
 default:throw Error('Unknown grade-six skill '+kind);
 }
}
