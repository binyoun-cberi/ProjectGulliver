(function timeToolsTests(){
  'use strict';
  const test=require('node:test');
  const assert=require('node:assert/strict');
  const fs=require('node:fs');
  const core=require('../time-tools-core.js');
  test('default clock options are safe and timer begins at five minutes',()=>{
    let now=1000;
    const engine=core.createEngine({},()=>now);
    assert.equal(engine.snapshot().mode,'timer');
    assert.equal(engine.snapshot().timeMs,300000);
    assert.equal(engine.data.learn.hour,3);
    assert.equal(engine.data.learn.minute,30);
    assert.equal(engine.data.events.reduce((s,e)=>s+e.durationSec,0),2400);
  });
  test('style switches and mode changes never reset in-progress time',()=>{
    let now=200000;
    const engine=core.createEngine({},()=>now);
    engine.start();now+=62340;
    assert.equal(engine.snapshot().remainingMs,237660);
    assert.equal(engine.setStyle('digital'),true);
    assert.equal(engine.snapshot().remainingMs,237660);
    assert.equal(engine.setStyle('analog'),false);
    engine.switchMode('stopwatch');
    assert.equal(engine.data.running,false);
    assert.equal(engine.elapsed('timer'),62340);
    engine.start();now+=1510;
    assert.equal(engine.snapshot().timeMs,1510);
    engine.switchMode('timer');
    assert.equal(engine.snapshot().remainingMs,237660);
    engine.start();now+=2340;
    assert.equal(engine.snapshot().remainingMs,235320);
  });
  test('saved running timer recovers from elapsed time and finishes accurately',()=>{
    let now=1000000;
    const engine=core.createEngine({},()=>now);
    engine.start();now+=20000;
    const saved=engine.save();
    now+=10000;
    const restored=core.createEngine(saved,()=>now);
    assert.equal(restored.snapshot().remainingMs,270000);
    now+=270001;
    assert.equal(restored.snapshot().remainingMs,0);
    assert.equal(restored.data.running,false);
  });
  test('legacy lesson schedule and stopwatch results are imported without destroying old keys',()=>{
    const legacySchedule={title:'우리반 시간표',events:[{name:'도입',durationSec:480,color:'#124578'},{name:'활동',durationSec:300}]};
    const oldRecords={stopwatch:{elapsed:2000,records:[{id:'a',name:'민',value:12540,createdAt:12345}]},timer:{duration:420000,remaining:300000,records:[{id:'b',name:'한',value:47000,createdAt:12345}]}};
    const imported=core.migrate(null,legacySchedule,oldRecords);
    const engine=core.createEngine(imported,()=>500000);
    assert.equal(engine.data.title,'우리반 시간표');
    assert.equal(engine.data.events[0].durationSec,480);
    assert.equal(engine.data.time.timer.durationMs,420000);
    assert.equal(engine.data.time.timer.elapsedMs,120000);
    assert.equal(engine.listRecords('stopwatch')[0].name,'민');
    assert.equal(engine.listRecords('timer')[0].valueMs,47000);
    assert.equal(engine.data.records.stopwatch.length,1);
  });
  test('lesson activities can advance and edit without modifying stopwatch records',()=>{
    let now=900;
    const engine=core.createEngine({},()=>now);
    engine.switchMode('lesson');engine.start();now+=30000;
    assert.equal(engine.snapshot().phase,'도입');
    engine.next();
    assert.equal(engine.snapshot().phase,'활동 1');
    assert.equal(engine.snapshot().running,true);
    engine.updateEvents([{name:'읽기',durationSec:120,color:'#123456'}]);
    assert.equal(engine.snapshot().phase,'읽기');
    assert.equal(engine.snapshot().running,false);
    assert.equal(engine.snapshot().remainingMs,120000);
  });
  test('public snapshot never exposes named stopwatch results or editable lesson details',()=>{
    let now=1000;
    const engine=core.createEngine({},()=>now);
    engine.switchMode('stopwatch');engine.start();now+=1800;
    assert.equal(engine.record('학생 이름'),true);
    assert.equal(engine.listRecords()[0].valueMs,1800);
    const view=JSON.stringify(engine.snapshot());
    assert.doesNotMatch(view,/학생 이름|createdAt|records|soundOn|teacherNote/);
    engine.switchMode('learn');engine.setLearning(11,25);
    assert.equal(engine.snapshot().reveal,false);
    assert.equal(engine.snapshot().hour,11);
    engine.setReveal(true);
    assert.equal(engine.snapshot().reveal,true);
  });
  test('timer leaderboard preserves legacy remaining-time ranking and rejects finished records',()=>{
    let now=10000;
    const engine=core.createEngine({},()=>now);
    engine.start();now+=10000;
    assert.equal(engine.record('빠른 학생'),true);
    assert.equal(engine.listRecords('timer')[0].valueMs,290000);
    now+=100000;
    assert.equal(engine.record('느린 학생'),true);
    assert.equal(engine.listRecords('timer')[0].name,'빠른 학생');
    assert.equal(engine.listRecords('timer')[1].valueMs,190000);
    now+=200000;
    assert.equal(engine.record('끝난 학생'),false);
    assert.equal(engine.listRecords('timer').length,2);
  });
  test('adjusting an active countdown and lesson does not interrupt the running clock',()=>{
    let now=1000;
    const engine=core.createEngine({},()=>now);
    engine.start();now+=25000;
    engine.adjust(60000);
    assert.equal(engine.snapshot().running,true);
    assert.equal(engine.snapshot().remainingMs,335000);
    now+=5000;
    assert.equal(engine.snapshot().remainingMs,330000);
    engine.switchMode('lesson');
    engine.start();now+=10000;
    engine.adjust(-60000);
    assert.equal(engine.snapshot().running,true);
    now+=1000;
    assert.equal(engine.snapshot().phase,'도입');
    assert.equal(engine.snapshot().remainingMs,2290000);
  });
  test('unified entry and second-screen rendering are wired without deleting old tool files',()=>{
    const html=fs.readFileSync('시간 도구.html','utf8');
    const view=fs.readFileSync('gulliver-teacher-display-view.js','utf8');
    const ui=fs.readFileSync('time-tools-ui.js','utf8');
    const catalog=fs.readFileSync('tools-catalog.js','utf8');
    assert.match(html,/time-tools-core\.js\?v=/);
    assert.match(html,/time-tools-ui\.js\?v=/);
    assert.match(html,/gulliver-teacher-display\.js\?v=/);
    assert.match(view,/data\?\.unified === true/);
    assert.match(view,/function renderUnifiedTime/);
    assert.match(ui,/GulliverTeacherDisplay\?\.register/);
    assert.equal((catalog.match(/href: "시간 도구\.html"/g)||[]).length,1);
    assert.equal(fs.existsSync('지도안식 원형 타이머.html'),true);
    assert.equal(fs.existsSync('시간 경쟁 시스템.html'),true);
  });
})();
